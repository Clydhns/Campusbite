import { PGlite } from '@electric-sql/pglite';
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';

const db = new PGlite();
let checks = 0;
const check = (condition, label) => { assert.ok(condition, label); checks++; console.log('PASS: ' + label); };
async function rejected(sql, label) {
  await assert.rejects(db.exec(sql));
  check(true, label);
}
try {
  // Supabase supplies these roles; create equivalents only in this in-memory test.
  await db.exec('CREATE ROLE anon; CREATE ROLE authenticated;');
  await db.exec(await readFile(new URL('../supabase/migrations/202610290001_initial_schema.sql', import.meta.url), 'utf8'));
  const tables = await db.query("SELECT relname,relrowsecurity FROM pg_class JOIN pg_namespace n ON n.oid=relnamespace WHERE n.nspname='public' AND relkind='r'");
  check(tables.rows.length === 12 && tables.rows.every(table => table.relrowsecurity), '12 PostgreSQL tables created with RLS enabled');
  const grants = await db.query("SELECT table_name FROM information_schema.table_privileges WHERE table_schema='public' AND grantee IN ('anon','authenticated','PUBLIC')");
  check(grants.rows.length === 0, 'No table grants expose account or order data through browser roles');
  await db.exec("INSERT INTO public.roles(role_id,role_name) VALUES (1,'Administrator'),(2,'Canteen Staff'),(3,'Student'); INSERT INTO public.categories(category_name) VALUES ('Meals'); INSERT INTO public.order_statuses(status_id,status_name) VALUES (1,'Pending');");
  await db.exec("INSERT INTO public.users(role_id,id_number,first_name,last_name,email,password_hash) VALUES (2,'FIXTURE-STAFF','Fixture','Staff','staff@example.invalid','not-a-real-password'),(3,'FIXTURE-STUDENT','Fixture','Student','student@example.invalid','not-a-real-password');");
  await rejected("INSERT INTO public.users(role_id,id_number,first_name,last_name,email,password_hash) VALUES (3,'FIXTURE-OTHER','Other','Fixture','STUDENT@EXAMPLE.INVALID','not-a-real-password')", 'Email uniqueness remains case-insensitive');
  await db.exec("INSERT INTO public.stores(staff_user_id,store_name) VALUES (1,'Fixture Kitchen'); INSERT INTO public.menu_items(category_id,item_name,price,store_id) VALUES (1,'Fixture Meal',50,1);");
  await rejected("INSERT INTO public.menu_items(category_id,item_name,price,store_id) VALUES (1,'fixture meal',50,1)", 'Food-name uniqueness remains case-insensitive within a store');
  await rejected("INSERT INTO public.menu_items(category_id,item_name,price,store_id) VALUES (1,'Zero Price',0,1)", 'Non-positive food prices are rejected');
  await db.exec("INSERT INTO public.daily_menu(menu_date,item_id,quantity_prepared,quantity_remaining) VALUES (CURRENT_DATE,1,5,5);");
  await rejected('UPDATE public.daily_menu SET quantity_remaining=6', 'Stock cannot exceed prepared servings');
  await rejected('UPDATE public.daily_menu SET quantity_remaining=-1', 'Stock cannot become negative');
  await db.exec("INSERT INTO public.orders(order_number,student_id,total_amount,store_id) VALUES ('FIXTURE-ORDER',2,100,1); INSERT INTO public.order_items(order_id,item_id,quantity,unit_price) VALUES (1,1,2,50);");
  const subtotal = await db.query('SELECT subtotal FROM public.order_items');
  check(Number(subtotal.rows[0].subtotal) === 100, 'Order-item subtotals are generated by PostgreSQL');
  await rejected('DELETE FROM public.menu_items WHERE item_id=1', 'Historical order references prevent unsafe food deletion');
  await db.exec("INSERT INTO public.payments(order_id,method,amount) VALUES (1,'GCash',100);");
  await rejected("UPDATE public.payments SET payment_status='Paid'", 'GCash cannot become paid without a reference');
  await db.exec("UPDATE public.payments SET reference_number='1234567890123',payment_status='Paid'; UPDATE public.users SET updated_at='2000-01-01';");
  const updated = await db.query("SELECT count(*) AS count FROM public.users WHERE updated_at>'2020-01-01'");
  check(Number(updated.rows[0].count) === 2, 'Updated-at triggers maintain timestamps');
  await db.exec('GRANT USAGE ON SCHEMA public TO anon; SET ROLE anon;');
  await rejected('SELECT password_hash FROM public.users', 'Anonymous role cannot read password hashes');
  await db.exec('RESET ROLE;');
  console.log(`${checks} embedded PostgreSQL schema checks passed. No remote database or customer data used.`);
} finally {
  await db.close();
}
