-- DRAFT: verify in a disposable PostgreSQL database before applying to Supabase.
-- Schema only. No account, password, order, or receipt records are included.
BEGIN;

CREATE TABLE public.roles (
    role_id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name varchar(30) NOT NULL UNIQUE,
    description varchar(150)
);
CREATE TABLE public.users (
    user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id smallint NOT NULL REFERENCES public.roles(role_id) ON UPDATE CASCADE,
    id_number varchar(20) NOT NULL UNIQUE,
    first_name varchar(50) NOT NULL,
    last_name varchar(50) NOT NULL,
    email varchar(100) NOT NULL,
    password_hash varchar(255) NOT NULL,
    contact_number varchar(15),
    grade_section varchar(30),
    is_active smallint NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
    created_at timestamp NOT NULL DEFAULT timezone('Asia/Manila', CURRENT_TIMESTAMP),
    updated_at timestamp NOT NULL DEFAULT timezone('Asia/Manila', CURRENT_TIMESTAMP)
);
CREATE UNIQUE INDEX uq_users_email ON public.users (lower(email));
CREATE INDEX idx_users_role ON public.users (role_id);

CREATE TABLE public.categories (
    category_id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name varchar(50) NOT NULL,
    description varchar(150)
);
CREATE UNIQUE INDEX uq_categories_name ON public.categories (lower(category_name));

CREATE TABLE public.order_statuses (
    status_id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status_name varchar(30) NOT NULL UNIQUE,
    description varchar(150)
);
CREATE TABLE public.stores (
    store_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_user_id bigint NOT NULL UNIQUE REFERENCES public.users(user_id),
    store_name varchar(100) NOT NULL,
    description varchar(255),
    gcash_number varchar(15),
    is_open smallint NOT NULL DEFAULT 1 CHECK (is_open IN (0,1)),
    created_at timestamp NOT NULL DEFAULT timezone('Asia/Manila', CURRENT_TIMESTAMP),
    gcash_qr_path varchar(255)
);
CREATE TABLE public.menu_items (
    item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id smallint NOT NULL REFERENCES public.categories(category_id) ON UPDATE CASCADE,
    item_name varchar(100) NOT NULL,
    description varchar(255),
    price numeric(8,2) NOT NULL CHECK (price > 0),
    is_available smallint NOT NULL DEFAULT 1 CHECK (is_available IN (0,1)),
    created_at timestamp NOT NULL DEFAULT timezone('Asia/Manila', CURRENT_TIMESTAMP),
    updated_at timestamp NOT NULL DEFAULT timezone('Asia/Manila', CURRENT_TIMESTAMP),
    store_id bigint NOT NULL REFERENCES public.stores(store_id),
    image_path varchar(255),
    archived_at timestamp
);
CREATE UNIQUE INDEX uq_store_item_name ON public.menu_items (store_id, lower(item_name));
CREATE INDEX idx_menu_items_category ON public.menu_items (category_id);

CREATE TABLE public.daily_menu (
    daily_menu_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_date date NOT NULL,
    item_id bigint NOT NULL REFERENCES public.menu_items(item_id) ON DELETE CASCADE ON UPDATE CASCADE,
    quantity_prepared integer NOT NULL DEFAULT 0 CHECK (quantity_prepared BETWEEN 0 AND 65535),
    quantity_remaining integer NOT NULL DEFAULT 0 CHECK (quantity_remaining BETWEEN 0 AND quantity_prepared),
    is_available smallint NOT NULL DEFAULT 1 CHECK (is_available IN (0,1)),
    created_at timestamp NOT NULL DEFAULT timezone('Asia/Manila', CURRENT_TIMESTAMP),
    updated_at timestamp NOT NULL DEFAULT timezone('Asia/Manila', CURRENT_TIMESTAMP),
    CONSTRAINT uq_daily_menu_date_item UNIQUE (menu_date,item_id)
);
CREATE INDEX idx_daily_menu_item ON public.daily_menu (item_id);

CREATE TABLE public.orders (
    order_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number varchar(20) NOT NULL UNIQUE,
    student_id bigint NOT NULL REFERENCES public.users(user_id) ON UPDATE CASCADE,
    staff_id bigint REFERENCES public.users(user_id) ON DELETE SET NULL ON UPDATE CASCADE,
    status_id smallint NOT NULL DEFAULT 1 REFERENCES public.order_statuses(status_id) ON UPDATE CASCADE,
    order_datetime timestamp NOT NULL DEFAULT timezone('Asia/Manila', CURRENT_TIMESTAMP),
    total_amount numeric(10,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
    remarks varchar(255),
    cancel_reason varchar(255),
    updated_at timestamp NOT NULL DEFAULT timezone('Asia/Manila', CURRENT_TIMESTAMP),
    store_id bigint NOT NULL REFERENCES public.stores(store_id)
);
CREATE INDEX idx_orders_student ON public.orders (student_id);
CREATE INDEX idx_orders_staff ON public.orders (staff_id);
CREATE INDEX idx_orders_status ON public.orders (status_id);
CREATE INDEX idx_orders_datetime ON public.orders (order_datetime);
CREATE INDEX idx_orders_store ON public.orders (store_id);

CREATE TABLE public.order_items (
    order_item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES public.orders(order_id) ON DELETE CASCADE ON UPDATE CASCADE,
    item_id bigint NOT NULL REFERENCES public.menu_items(item_id) ON UPDATE CASCADE,
    quantity integer NOT NULL DEFAULT 1 CHECK (quantity BETWEEN 1 AND 65535),
    unit_price numeric(8,2) NOT NULL CHECK (unit_price >= 0),
    subtotal numeric(10,2) GENERATED ALWAYS AS (quantity * unit_price) STORED,
    CONSTRAINT uq_order_items_order_item UNIQUE (order_id,item_id)
);
CREATE INDEX idx_order_items_item ON public.order_items (item_id);

CREATE TABLE public.payments (
    payment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL UNIQUE REFERENCES public.orders(order_id) ON DELETE CASCADE ON UPDATE CASCADE,
    method varchar(5) NOT NULL CHECK (method IN ('Cash','GCash')),
    amount numeric(10,2) NOT NULL CHECK (amount >= 0),
    reference_number varchar(30) UNIQUE,
    payment_status varchar(8) NOT NULL DEFAULT 'Unpaid' CHECK (payment_status IN ('Unpaid','Paid','Refunded')),
    received_by bigint REFERENCES public.users(user_id) ON DELETE SET NULL ON UPDATE CASCADE,
    created_at timestamp NOT NULL DEFAULT timezone('Asia/Manila', CURRENT_TIMESTAMP),
    paid_at timestamp,
    receipt_path varchar(255),
    receipt_submitted_at timestamp,
    payment_rejected_at timestamp,
    payment_rejection_reason varchar(255),
    CONSTRAINT chk_payments_gcash_ref CHECK (method='Cash' OR payment_status='Unpaid' OR reference_number IS NOT NULL)
);
CREATE INDEX idx_payments_received_by ON public.payments (received_by);
CREATE INDEX idx_payments_status ON public.payments (payment_status);

CREATE TABLE public.order_status_logs (
    log_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES public.orders(order_id) ON DELETE CASCADE ON UPDATE CASCADE,
    status_id smallint NOT NULL REFERENCES public.order_statuses(status_id) ON UPDATE CASCADE,
    changed_by bigint REFERENCES public.users(user_id) ON DELETE SET NULL ON UPDATE CASCADE,
    changed_at timestamp NOT NULL DEFAULT timezone('Asia/Manila', CURRENT_TIMESTAMP),
    note varchar(255)
);
CREATE INDEX idx_logs_order ON public.order_status_logs (order_id);
CREATE INDEX idx_logs_status ON public.order_status_logs (status_id);
CREATE INDEX idx_logs_changed_by ON public.order_status_logs (changed_by);

CREATE TABLE public.sales_records (
    sale_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL UNIQUE REFERENCES public.orders(order_id) ON UPDATE CASCADE,
    sale_date date NOT NULL,
    total_amount numeric(10,2) NOT NULL CHECK (total_amount >= 0),
    recorded_at timestamp NOT NULL DEFAULT timezone('Asia/Manila', CURRENT_TIMESTAMP)
);
CREATE INDEX idx_sales_date ON public.sales_records (sale_date);

CREATE FUNCTION public.cb_set_updated_at() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
    NEW.updated_at := timezone('Asia/Manila', CURRENT_TIMESTAMP);
    RETURN NEW;
END;
$$;
CREATE TRIGGER users_updated_at BEFORE UPDATE ON public.users FOR EACH ROW EXECUTE FUNCTION public.cb_set_updated_at();
CREATE TRIGGER menu_items_updated_at BEFORE UPDATE ON public.menu_items FOR EACH ROW EXECUTE FUNCTION public.cb_set_updated_at();
CREATE TRIGGER daily_menu_updated_at BEFORE UPDATE ON public.daily_menu FOR EACH ROW EXECUTE FUNCTION public.cb_set_updated_at();
CREATE TRIGGER orders_updated_at BEFORE UPDATE ON public.orders FOR EACH ROW EXECUTE FUNCTION public.cb_set_updated_at();

ALTER TABLE public.roles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.order_statuses ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.stores ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.menu_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.daily_menu ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.order_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.payments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.order_status_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sales_records ENABLE ROW LEVEL SECURITY;

-- Custom PHP authentication does not produce Supabase Auth JWTs. Deny direct
-- client access until a reviewed role/policy design is implemented.
REVOKE ALL ON TABLE public.roles, public.users, public.categories,
    public.order_statuses, public.stores, public.menu_items, public.daily_menu,
    public.orders, public.order_items, public.payments, public.order_status_logs,
    public.sales_records FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.cb_set_updated_at() FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.roles_role_id_seq, public.users_user_id_seq,
    public.categories_category_id_seq, public.order_statuses_status_id_seq,
    public.stores_store_id_seq, public.menu_items_item_id_seq,
    public.daily_menu_daily_menu_id_seq, public.orders_order_id_seq,
    public.order_items_order_item_id_seq, public.payments_payment_id_seq,
    public.order_status_logs_log_id_seq, public.sales_records_sale_id_seq
    FROM PUBLIC, anon, authenticated;

COMMIT;
